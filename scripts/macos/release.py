#!/usr/bin/env python3
"""Prepare and notarize independent Code-Codex ARM64 releases on macOS."""

import argparse
from contextlib import contextmanager
import fcntl
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import stat
import struct
import subprocess
import sys
import tempfile

from package import (BUNDLE_ID, MIN_MACOS, PRODUCT, RESOURCE_FILES,
                     STORAGE_LAYOUT_CONTENT, STORAGE_LAYOUT_NAME, rename_exclusive)


APP = PRODUCT + '.app'
CORE = 'code-codex-core'
RECEIPT = 'notarization.json'
CODESIGN = '/usr/bin/codesign'
XCRUN = '/usr/bin/xcrun'
DITTO = '/usr/bin/ditto'
UUID = r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}'


class ReleaseError(Exception):
    pass


def run(*args, timeout=60, check=True):
    result = subprocess.run(args, stdin=subprocess.DEVNULL, capture_output=True, text=True,
                            timeout=timeout, env={**os.environ, 'LC_ALL': 'C'})
    if check and result.returncode:
        command = ' '.join(map(str, args[:3] if args[0] == XCRUN else args[:2]))
        detail = result.stderr.strip()[-1000:]
        raise ReleaseError(f'{command} failed (exit {result.returncode}): {detail}')
    return result


def validate_version(version):
    if not isinstance(version, str) or not re.fullmatch(r'(0|[1-9][0-9]*)(\.(0|[1-9][0-9]*)){2}', version):
        raise ReleaseError('Version must have three numeric components without leading zeros')


def validate_team(team):
    if not isinstance(team, str) or not re.fullmatch(r'[A-Z0-9]{10}', team):
        raise ReleaseError('Expected a 10-character Developer Team ID')


def validate_file(path):
    if not stat.S_ISREG(path.lstat().st_mode):
        raise ReleaseError(f'Expected a regular file: {path}')


def validate_directory(path):
    if not stat.S_ISDIR(path.lstat().st_mode):
        raise ReleaseError(f'Expected a regular directory: {path}')


def validate_executable(path):
    validate_file(path)
    if not path.stat().st_mode & stat.S_IXUSR:
        raise ReleaseError(f'Expected an executable file: {path}')
    with path.open('rb') as executable:
        header = executable.read(16)
    # MH_MAGIC_64, CPU_TYPE_ARM64, CPU_SUBTYPE_ARM64_ALL (or V8), MH_EXECUTE.
    if (len(header) != 16 or struct.unpack('<4I', header) not in
            ((0xfeedfacf, 0x0100000c, 0, 2), (0xfeedfacf, 0x0100000c, 1, 2))):
        raise ReleaseError(f'Expected a thin ARM64 Mach-O executable: {path.name}')
    build = run(XCRUN, 'vtool', '-show-build', path).stdout
    minimum = re.findall(r'^\s*minos\s+(\d+)\.(\d+)(?:\.(\d+))?\s*$', build, re.MULTILINE)
    platform = re.findall(r'^\s*platform\s+(\w+)\s*$', build, re.MULTILINE)
    if (platform != ['MACOS'] or len(minimum) != 1 or
            tuple(int(number or 0) for number in minimum[0]) >
            (*map(int, MIN_MACOS.split('.')), 0)):
        raise ReleaseError(f'{path.name} must declare a minimum macOS version of {MIN_MACOS} or earlier')


def validate_storage_marker(path):
    # Release input uses the exact marker generated by our packager.
    with path.open('rb') as marker:
        raw = marker.read(4097)
    if len(raw) > 4096:
        raise ReleaseError('Invalid storage layout marker: exceeds 4096 bytes')
    if raw != STORAGE_LAYOUT_CONTENT:
        raise ReleaseError('Invalid storage layout marker: expected the project packager output')


def check_app(app, version):
    validate_version(version)
    if app.name != APP:
        raise ReleaseError(f'Expected the project bundle named {APP}')
    validate_directory(app)
    contents = app/'Contents'
    validate_directory(contents)
    expected_dirs = {'MacOS', 'Resources', '_CodeSignature'}
    expected_entries = expected_dirs | {'Info.plist'}
    if ({path.name for path in app.iterdir()} != {'Contents'} or
            {path.name for path in contents.iterdir()} - {'CodeResources'} != expected_entries):
        raise ReleaseError('Unexpected project app bundle layout')
    for name in expected_dirs:
        validate_directory(contents/name)
    for path, names in (
        (contents/'MacOS', {PRODUCT, CORE}),
        (contents/'Resources', set(RESOURCE_FILES) | {STORAGE_LAYOUT_NAME}),
        (contents/'_CodeSignature', {'CodeResources'}),
    ):
        if {item.name for item in path.iterdir()} != names:
            raise ReleaseError(f'Unexpected project app bundle layout in {path.name}')
        for item in path.iterdir():
            validate_file(item)
    validate_storage_marker(contents/'Resources'/STORAGE_LAYOUT_NAME)
    if os.path.lexists(contents/'CodeResources'):
        validate_file(contents/'CodeResources')  # Apple's stapled ticket, when present.
    info_path = contents/'Info.plist'
    validate_file(info_path)
    info = plistlib.loads(info_path.read_bytes())
    expected = {'CFBundleIdentifier': BUNDLE_ID, 'CFBundleName': PRODUCT,
                'CFBundleDisplayName': PRODUCT, 'CFBundleExecutable': PRODUCT,
                'CFBundlePackageType': 'APPL', 'CFBundleShortVersionString': version,
                'CFBundleVersion': version, 'LSMinimumSystemVersion': MIN_MACOS}
    for key, value in expected.items():
        if not isinstance(info, dict) or info.get(key) != value:
            raise ReleaseError(f'Unexpected {key} (expected {value})')
    launcher, core = (contents/'MacOS'/name for name in (PRODUCT, CORE))
    for code in (launcher, core):
        validate_executable(code)
    run(CODESIGN, '--verify', '--strict', '--deep', app)
    return core


def confirm_identity(identity, team):
    validate_team(team)
    if not re.fullmatch(r'[a-fA-F0-9]{40}', identity):
        raise ReleaseError('Identity must be the 40-character Developer ID Application certificate fingerprint')
    identities = run('/usr/bin/security', 'find-identity', '-v', '-p', 'codesigning').stdout
    for digest, name in re.findall(r'^\s*\d+\)\s+([A-Fa-f0-9]{40})\s+"([^"\n]+)"\s*$',
                                   identities, re.MULTILINE):
        if digest.upper() == identity.upper() and name.startswith('Developer ID Application: '):
            label = name.removeprefix('Developer ID Application: ')
            if label == team or label.endswith(f' ({team})'):
                return digest.upper()
    raise ReleaseError('A valid Developer ID Application identity for the expected team was not found')


def verify_distribution(path, team, *, runtime=False, identifier=None):
    requirement = ('=anchor apple generic and certificate 1[field.1.2.840.113635.100.6.2.6] exists'
                   ' and certificate leaf[field.1.2.840.113635.100.6.1.13] exists'
                   f' and certificate leaf[subject.OU] = "{team}"')
    if identifier is not None:
        requirement += f' and identifier "{identifier}"'
    run(CODESIGN, '--verify', '--strict', '-R', requirement, path)
    details = run(CODESIGN, '--display', '--verbose=4', path).stderr
    if (not re.search(r'^Timestamp=[^\r\n]+$', details, re.MULTILINE) or
            f'TeamIdentifier={team}' not in details.splitlines()):
        raise ReleaseError(f'Expected a timestamped Developer ID signature for {team}: {path.name}')
    if runtime:
        flags = re.search(r'^CodeDirectory .* flags=0x([a-fA-F0-9]+)', details, re.MULTILINE)
        cdhash = re.search(r'^CDHash=([a-f0-9]{40})$', details, re.MULTILINE)
        if not (flags and int(flags.group(1), 16) & 0x10000 and cdhash):
            raise ReleaseError(f'Expected Hardened Runtime and an Apple code directory hash: {path.name}')
        return cdhash.group(1)


def verify_signed_app(app, version, team):
    core = check_app(app, version)
    return {
        PRODUCT: verify_distribution(app, team, runtime=True, identifier=BUNDLE_ID),
        CORE: verify_distribution(core, team, runtime=True, identifier=BUNDLE_ID + '.' + CORE),
    }


def work_path(path):
    absolute = path.absolute()
    resolved = absolute.resolve()
    if any(part.suffix.casefold() == '.app'
           for location in (absolute, resolved) for part in (location, *location.parents)):
        raise ReleaseError('Release output must be outside any app bundle')
    if absolute.is_symlink():
        raise ReleaseError('Release output must be a regular directory, not a symlink')
    return resolved


def asset_details(path):
    validate_file(path)
    sha256 = hashlib.sha256()
    with path.open('rb') as asset:
        for chunk in iter(lambda: asset.read(1024*1024), b''):
            sha256.update(chunk)
        size = asset.tell()
    return {'size': size, 'sha256': sha256.hexdigest()}


def update_receipt(work, receipt):
    # A crash cannot leave a partially written state or allow an upload to be retried blindly.
    with tempfile.TemporaryDirectory(prefix='.receipt-', dir=work) as stage:
        temporary = Path(stage)/RECEIPT
        with temporary.open('w') as output:
            json.dump(receipt, output, indent=2, sort_keys=True)
            output.write('\n')
            output.flush()
            os.fsync(output.fileno())
        temporary.replace(work/RECEIPT)
        directory = os.open(work, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)


def prepare(args):
    if os.path.lexists(args.output):
        raise ReleaseError('Release output already exists; choose a new directory')
    work = work_path(args.output)
    source = args.app.absolute()
    check_app(source, args.version)
    identity = confirm_identity(args.identity, args.team_id)
    work.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.release-prepare-', dir=work.parent) as temp:
        stage = Path(temp)
        payload = stage/'payload'
        payload.mkdir()
        app = payload/APP
        run(DITTO, source, app)
        core = check_app(app, args.version)
        for code in (core, app):
            identifier = BUNDLE_ID if code == app else BUNDLE_ID + '.' + CORE
            run(CODESIGN, '--force', '--sign', identity, '--identifier', identifier,
                '--options', 'runtime', '--timestamp', code, timeout=120)
        cdhashes = verify_signed_app(app, args.version, args.team_id)
        dmg = stage/f'{PRODUCT}-{args.version}-arm64.dmg'
        run('/usr/bin/hdiutil', 'create', '-quiet', '-fs', 'HFS+', '-format', 'UDZO',
            '-volname', PRODUCT, '-srcfolder', payload, dmg, timeout=300)
        run(CODESIGN, '--sign', identity, '--timestamp', dmg, timeout=120)
        verify_distribution(dmg, args.team_id)
        (stage/'.release.lock').touch(mode=0o600, exist_ok=False)
        update_receipt(stage, {'schema': 1, 'product': PRODUCT, 'bundle_id': BUNDLE_ID,
                               'version': args.version, 'architecture': 'arm64', 'minimum_macos': MIN_MACOS,
                               'team_id': args.team_id, 'status': 'prepared', 'submission_id': None,
                               'submitted_asset': {'name': dmg.name, **asset_details(dmg)},
                               'code_directory_hashes': cdhashes})
        rename_exclusive(stage, work)
    print(f'Signed candidate prepared at {work}; ready for an explicit submit command.')


@contextmanager
def locked_work(path):
    work = work_path(path)
    validate_directory(work)
    lock_path = work/'.release.lock'
    with os.fdopen(os.open(lock_path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), 'rb') as lock:
        if not stat.S_ISREG(os.fstat(lock.fileno()).st_mode):
            raise ReleaseError('Expected a regular release lock file')
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as error:
            raise ReleaseError('Another release operation is running') from error
        receipt_path = work/RECEIPT
        validate_file(receipt_path)
        receipt = json.loads(receipt_path.read_text())
        if (not isinstance(receipt, dict) or receipt.get('schema') != 1 or
                receipt.get('product') != PRODUCT or receipt.get('bundle_id') != BUNDLE_ID or
                receipt.get('architecture') != 'arm64' or receipt.get('minimum_macos') != MIN_MACOS):
            raise ReleaseError('Unrecognized release receipt')
        validate_version(receipt.get('version'))
        validate_team(receipt.get('team_id'))
        yield work, receipt


def verify_candidate_dmg(dmg, receipt):
    if receipt.get('submitted_asset') != {'name': dmg.name, **asset_details(dmg)}:
        raise ReleaseError('Candidate DMG does not match the prepared receipt')
    verify_distribution(dmg, receipt['team_id'])


def check_candidate(work, receipt):
    dmg = work/f'{PRODUCT}-{receipt["version"]}-arm64.dmg'
    verify_candidate_dmg(dmg, receipt)
    validate_directory(work/'payload')
    app = work/'payload'/APP
    if verify_signed_app(app, receipt['version'], receipt['team_id']) != receipt.get('code_directory_hashes'):
        raise ReleaseError('Candidate app does not match the prepared receipt')
    return app, dmg


def notary(profile, operation, *args, **kwargs):
    return run(XCRUN, 'notarytool', operation, *args, '--keychain-profile', profile, **kwargs)


def parse_submission_id(output):
    if isinstance(output, bytes):
        output = output.decode(errors='replace')
    match = re.search(r'"id"\s*:\s*"('+UUID+r')"|^\s*id:\s*('+UUID+r')\s*$',
                      output or '', re.IGNORECASE | re.MULTILINE)
    return (match.group(1) or match.group(2)).lower() if match else None


def submit(work, receipt, profile):
    if receipt.get('status') != 'prepared':
        raise ReleaseError('Release already has a submission attempt; continue with finish')
    _, dmg = check_candidate(work, receipt)
    with tempfile.TemporaryDirectory(prefix='.release-submit-', dir=work) as stage:
        snapshot = Path(stage)/dmg.name
        run(DITTO, dmg, snapshot)
        verify_candidate_dmg(snapshot, receipt)
        receipt['status'] = 'submission-unknown'
        update_receipt(work, receipt)
        try:
            result = notary(profile, 'submit', snapshot, '--output-format', 'json', '--no-wait',
                            timeout=300, check=False)
        except subprocess.TimeoutExpired as error:
            result = subprocess.CompletedProcess(error.cmd, 1, error.output, error.stderr)
        submission_id = parse_submission_id(result.stdout)
        if submission_id:
            receipt.update(status='pending', submission_id=submission_id)
            update_receipt(work, receipt)
    if not submission_id:
        raise ReleaseError('Upload outcome is unknown. Check notarytool history and recover with finish --submission-id.')
    if result.returncode:
        raise ReleaseError(f'Upload returned an error after reporting {submission_id}. Continue with finish.')
    print(f'Apple submission {submission_id} is pending at {work}.')


def notarization_log(profile, submission_id, dmg, receipt, status):
    result = notary(profile, 'log', submission_id)
    log = json.loads(result.stdout)
    if (not isinstance(log, dict) or str(log.get('jobId', '')).lower() != submission_id or
            log.get('status') != status or log.get('archiveFilename') != dmg.name or
            str(log.get('sha256', '')).lower() != receipt['submitted_asset']['sha256']):
        raise ReleaseError('Apple notarization log does not match this submitted DMG and job')
    if status == 'Accepted':
        tickets = log.get('ticketContents')
        if not isinstance(tickets, list) or not any(
            isinstance(ticket, dict) and ticket.get('arch') == 'arm64' and
            ticket.get('cdhash') == receipt['code_directory_hashes'][PRODUCT] for ticket in tickets
        ):
            raise ReleaseError('Apple notarization log is missing the ARM64 app ticket')
    return log


def publish(work, receipt, app, dmg, log):
    destination = work/'dist'
    with tempfile.TemporaryDirectory(prefix='.release-finish-', dir=work) as temp:
        stage = Path(temp)
        dist = stage/'dist'
        dist.mkdir()
        final_app, final_dmg = dist/APP, dist/dmg.name
        run(DITTO, app, final_app)
        run(DITTO, dmg, final_dmg)
        verify_candidate_dmg(final_dmg, receipt)
        if verify_signed_app(final_app, receipt['version'], receipt['team_id']) != receipt['code_directory_hashes']:
            raise ReleaseError('Staged distribution differs from the accepted candidate')
        for asset in (final_app, final_dmg):
            run(XCRUN, 'stapler', 'staple', asset, timeout=120)
            run(XCRUN, 'stapler', 'validate', asset, timeout=120)
        verify_distribution(final_dmg, receipt['team_id'])
        run('/usr/bin/hdiutil', 'verify', '-quiet', final_dmg, timeout=300)
        final_zip = final_dmg.with_suffix('.zip')
        run(DITTO, '-c', '-k', '--sequesterRsrc', '--keepParent', final_app, final_zip, timeout=300)
        unzipped = stage/'unzipped'
        run(DITTO, '-x', '-k', final_zip, unzipped, timeout=300)
        for candidate in (final_app, unzipped/APP):
            if verify_signed_app(candidate, receipt['version'], receipt['team_id']) != receipt['code_directory_hashes']:
                raise ReleaseError('Final app differs from the accepted candidate')
        run(XCRUN, 'stapler', 'validate', unzipped/APP, timeout=120)
        assets = {asset.name: asset_details(asset) for asset in (final_dmg, final_zip)}
        (dist/'SHA256SUMS').write_text(''.join(f'{detail["sha256"]}  {name}\n' for name, detail in assets.items()))
        (dist/'apple-notarization.json').write_text(json.dumps(log, indent=2, sort_keys=True)+'\n')
        release = {**receipt, 'status': 'release-ready', 'assets': assets,
                   'standalone_app': {'name': APP, 'stapled': True}}
        (dist/'release.json').write_text(json.dumps(release, indent=2, sort_keys=True)+'\n')
        rename_exclusive(dist, destination)
    print(f'Verified release artifacts at {destination}.')


def finish(work, receipt, profile, recovery_id):
    if os.path.lexists(work/'dist'):
        raise ReleaseError('Final release output already exists')
    status = receipt.get('status')
    if status not in ('pending', 'submission-unknown', 'accepted'):
        raise ReleaseError('Expected a pending, ambiguous, or accepted notarization attempt')
    if recovery_id and (status != 'submission-unknown' or receipt.get('submission_id')):
        raise ReleaseError('A recovery submission ID is only valid after an ambiguous upload without an ID')
    submission_id = recovery_id or receipt.get('submission_id') or receipt.get('recovery_submission_id')
    if not isinstance(submission_id, str) or not re.fullmatch(UUID, submission_id, re.IGNORECASE):
        raise ReleaseError('Expected the Apple submission UUID; recover an unknown ID using notarytool history')
    submission_id = submission_id.lower()
    app, dmg = check_candidate(work, receipt)
    result = notary(profile, 'info', submission_id, '--output-format', 'json')
    info = json.loads(result.stdout)
    if (not isinstance(info, dict) or str(info.get('id', '')).lower() != submission_id or
            info.get('name') != dmg.name):
        raise ReleaseError('Apple submission details do not match the candidate')
    status = info.get('status')
    if status == 'In Progress':
        if recovery_id:
            receipt['recovery_submission_id'] = submission_id
            update_receipt(work, receipt)
        print(f'Apple submission {submission_id} is pending. Run finish again after processing completes.')
        return 2
    if status not in ('Accepted', 'Invalid', 'Rejected'):
        raise ReleaseError('Apple returned an unrecognized notarization status')
    log = notarization_log(profile, submission_id, dmg, receipt, status)
    receipt.pop('recovery_submission_id', None)
    receipt.update(status='accepted' if status == 'Accepted' else 'failed', submission_id=submission_id,
                   apple_status=status)
    update_receipt(work, receipt)
    if status != 'Accepted':
        raise ReleaseError(f'Apple returned {status} for {submission_id}. Inspect its notarization log.')
    publish(work, receipt, app, dmg, log)
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    check = commands.add_parser('check', help='read-only validation of a locally packaged app')
    preparation = commands.add_parser('prepare', help='sign a copy and create a signed candidate DMG')
    for command in (check, preparation):
        command.add_argument('--app', type=Path, required=True)
        command.add_argument('--version', required=True)
    preparation.add_argument('--output', type=Path, required=True, help='new release work directory')
    preparation.add_argument('--team-id', required=True, help='expected Developer Team ID')
    preparation.add_argument('--identity', required=True, help='Developer ID Application certificate fingerprint')
    for name, help_text in [('submit', 'upload a prepared candidate once'),
                            ('finish', 'check acceptance and staple the release artifacts')]:
        command = commands.add_parser(name, help=help_text)
        command.add_argument('--work', type=Path, required=True, help='prepared release work directory')
        command.add_argument('--keychain-profile', required=True, help='existing notarytool Keychain profile name')
        if name == 'finish':
            command.add_argument('--submission-id', help='Apple UUID recovered from notarytool history')
    args = parser.parse_args(argv)
    try:
        if args.command == 'check':
            check_app(args.app.absolute(), args.version)
            print(f'Checked {APP} {args.version}, ARM64, minimum macOS {MIN_MACOS}.')
        elif args.command == 'prepare':
            prepare(args)
        else:
            if not args.keychain_profile.strip() or args.keychain_profile.startswith('-'):
                raise ReleaseError('Expected a Keychain profile name')
            with locked_work(args.work) as (work, receipt):
                if args.command == 'submit':
                    submit(work, receipt, args.keychain_profile)
                else:
                    return finish(work, receipt, args.keychain_profile, args.submission_id)
    except subprocess.TimeoutExpired as error:
        command = ' '.join(map(str, error.cmd[:3] if error.cmd[0] == XCRUN else error.cmd[:2]))
        print(f'Error: {command} timed out after {error.timeout} seconds.', file=sys.stderr)
        return 1
    except (ReleaseError, OSError, ValueError, plistlib.InvalidFileException) as error:
        print(f'Error: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
